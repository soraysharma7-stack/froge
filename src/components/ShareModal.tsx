import React, { useState } from 'react';
import {
  X,
  Copy,
  Check,
  Download,
  Share2,
  FileCode,
  FileText,
  Printer,
  Link,
} from 'lucide-react';
import { ChatMessage, Conversation } from '../types';
import { FrogeLogo } from './FrogeLogo';

interface ShareModalProps {
  isOpen: boolean;
  onClose: () => void;
  message?: ChatMessage | null;
  conversation?: Conversation | null;
}

export const ShareModal: React.FC<ShareModalProps> = ({
  isOpen,
  onClose,
  message,
  conversation,
}) => {
  const [copiedLink, setCopiedLink] = useState(false);
  const [copiedText, setCopiedText] = useState(false);

  if (!isOpen) return null;

  const getExportMarkdown = () => {
    if (message) {
      return `### FROGÉ AI Response (${message.mode})\n\n${message.content}\n\n*Generated by FROGÉ App 1*`;
    }
    if (conversation) {
      let doc = `# ${conversation.title}\n\n**Mode**: ${conversation.mode}  \n**Date**: ${new Date(
        conversation.createdAt
      ).toLocaleDateString()}\n\n---\n\n`;
      for (const msg of conversation.messages) {
        doc += `### ${msg.role === 'user' ? 'User' : 'FROGÉ AI'}\n\n${msg.content}\n\n---\n\n`;
      }
      return doc;
    }
    return '';
  };

  const handleCopyMarkdown = () => {
    navigator.clipboard.writeText(getExportMarkdown());
    setCopiedText(true);
    setTimeout(() => setCopiedText(false), 2000);
  };

  const handleCopyShareLink = () => {
    navigator.clipboard.writeText(window.location.href);
    setCopiedLink(true);
    setTimeout(() => setCopiedLink(false), 2000);
  };

  const handleDownloadFile = (ext: 'md' | 'json') => {
    const text =
      ext === 'json'
        ? JSON.stringify(conversation || message, null, 2)
        : getExportMarkdown();

    const blob = new Blob([text], {
      type: ext === 'json' ? 'application/json' : 'text/markdown',
    });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `froge_export_${Date.now()}.${ext}`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/40 backdrop-blur-xs animate-fade-in select-none">
      <div
        id="froge-share-modal"
        className="w-full max-w-md bg-white/95 backdrop-blur-xl rounded-3xl border border-slate-200 shadow-2xl p-6 relative animate-scale-in"
      >
        <button
          onClick={onClose}
          className="absolute right-4 top-4 p-2 text-slate-400 hover:text-slate-700 hover:bg-slate-100 rounded-full transition-colors"
        >
          <X className="w-5 h-5" />
        </button>

        <div className="flex items-center gap-3 mb-4">
          <FrogeLogo size="sm" showBadge={false} />
          <div>
            <h3 className="text-base font-bold text-slate-900">
              {message ? 'Share Response' : 'Share Conversation'}
            </h3>
            <p className="text-xs text-slate-500">
              Export or share your FROGÉ workspace content
            </p>
          </div>
        </div>

        <div className="space-y-3 my-6">
          {/* Quick Copy Link */}
          <button
            onClick={handleCopyShareLink}
            className="w-full flex items-center justify-between p-3.5 rounded-xl border border-slate-200 hover:border-emerald-300 hover:bg-slate-50 transition-colors text-xs font-medium text-slate-800"
          >
            <div className="flex items-center gap-2.5">
              <Link className="w-4 h-4 text-emerald-600" />
              <span>Copy Applet Share Link</span>
            </div>
            {copiedLink ? (
              <span className="flex items-center gap-1 text-emerald-600 font-semibold">
                <Check className="w-3.5 h-3.5" /> Copied
              </span>
            ) : (
              <span className="text-slate-400">Copy</span>
            )}
          </button>

          {/* Copy Markdown Text */}
          <button
            onClick={handleCopyMarkdown}
            className="w-full flex items-center justify-between p-3.5 rounded-xl border border-slate-200 hover:border-emerald-300 hover:bg-slate-50 transition-colors text-xs font-medium text-slate-800"
          >
            <div className="flex items-center gap-2.5">
              <FileText className="w-4 h-4 text-blue-600" />
              <span>Copy Formatted Markdown</span>
            </div>
            {copiedText ? (
              <span className="flex items-center gap-1 text-emerald-600 font-semibold">
                <Check className="w-3.5 h-3.5" /> Copied
              </span>
            ) : (
              <span className="text-slate-400">Copy</span>
            )}
          </button>

          {/* Download Options */}
          <div className="grid grid-cols-2 gap-2 pt-2">
            <button
              onClick={() => handleDownloadFile('md')}
              className="flex items-center justify-center gap-2 p-3 rounded-xl border border-slate-200 hover:bg-slate-50 text-xs font-medium text-slate-700 transition-colors"
            >
              <Download className="w-3.5 h-3.5 text-slate-500" />
              <span>Export .MD</span>
            </button>
            <button
              onClick={() => handleDownloadFile('json')}
              className="flex items-center justify-center gap-2 p-3 rounded-xl border border-slate-200 hover:bg-slate-50 text-xs font-medium text-slate-700 transition-colors"
            >
              <FileCode className="w-3.5 h-3.5 text-slate-500" />
              <span>Export JSON</span>
            </button>
          </div>
        </div>

        <div className="pt-3 border-t border-slate-100 flex items-center justify-between text-xs text-slate-400">
          <span>Client-side export</span>
          <button
            onClick={handlePrint}
            className="flex items-center gap-1 text-slate-500 hover:text-slate-800"
          >
            <Printer className="w-3.5 h-3.5" />
            <span>Print View</span>
          </button>
        </div>
      </div>
    </div>
  );
};
